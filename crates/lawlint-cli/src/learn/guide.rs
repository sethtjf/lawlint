//! `STYLE.md`: the mined style as a drafting brief.
//!
//! Rules catch deviations after a draft exists. Agents write better first
//! drafts when they see the target before writing, so the package also ships
//! the same knowledge as prose: the measured profile (with the AI-draft
//! comparison when a contrast set ran), the connectives the corpus uses and
//! avoids, and every kept rule with its examples. Generated deterministically
//! from what the run already computed; no extra model call.

use std::fmt::Write as _;
use std::path::Path;

use super::profile::{passage_label, rate_label, StyleProfile};
use super::Candidate;

fn capitalized(text: &str) -> String {
    let mut chars = text.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

pub(super) fn style_guide(
    package: &str,
    corpus_label: &str,
    out: &Path,
    profile: &StyleProfile,
    contrast: Option<&StyleProfile>,
    kept: &[Candidate],
) -> String {
    let out = out.display();
    let mut doc = String::new();
    let _ = writeln!(doc, "# Writing style: {package}\n");
    let _ = writeln!(
        doc,
        "Generated by `lawlint learn` from {corpus_label} ({} text{}, ~{} words). \
         This is the target style for drafts: read it before writing, then let \
         lawlint check the result against the same rules. Regenerate it by rerunning \
         `lawlint learn`; edits here are overwritten.\n",
        profile.texts,
        if profile.texts == 1 { "" } else { "s" },
        profile.words
    );
    doc.push_str("## Workflow\n\n");
    let _ = writeln!(
        doc,
        "1. Draft with this file in context.\n\
         2. Lint the draft: `lawlint --rule-dir {out} draft.md`.\n\
         3. Hand the findings back for revision: `lawlint --rule-dir {out} --format prompt draft.md`.\n\
         4. Repeat until the draft is clean.\n"
    );

    doc.push_str("## Measured style\n\n");
    if contrast.is_some() {
        doc.push_str(
            "The AI-drafts column measures the configured model's own versions of \
             sampled source passages. Where the columns differ, write like the source.\n\n",
        );
        doc.push_str("| Measure | Source | AI drafts |\n| --- | ---: | ---: |\n");
    } else {
        doc.push_str("| Measure | Source |\n| --- | ---: |\n");
    }
    let mut row =
        |label: &str, ours: String, theirs: Option<String>| match (contrast.is_some(), theirs) {
            (true, theirs) => {
                let _ = writeln!(doc, "| {label} | {ours} | {} |", theirs.unwrap_or_default());
            }
            (false, _) => {
                let _ = writeln!(doc, "| {label} | {ours} |");
            }
        };
    row(
        "Words per sentence (median)",
        profile.sentence_words.median.to_string(),
        contrast.map(|c| c.sentence_words.median.to_string()),
    );
    row(
        "Words per sentence (middle 80%)",
        format!(
            "{}–{}",
            profile.sentence_words.p10, profile.sentence_words.p90
        ),
        contrast.map(|c| format!("{}–{}", c.sentence_words.p10, c.sentence_words.p90)),
    );
    row(
        "Longest sentence (words)",
        profile.sentence_words.max.to_string(),
        contrast.map(|c| c.sentence_words.max.to_string()),
    );
    row(
        "Sentences per paragraph (mean)",
        profile.paragraph_sentences.mean.to_string(),
        contrast.map(|c| c.paragraph_sentences.mean.to_string()),
    );
    for (key, value) in &profile.rates {
        let theirs = contrast.and_then(|c| c.rates.get(key).copied());
        if *value == 0.0 && theirs.unwrap_or(0.0) == 0.0 {
            continue;
        }
        row(
            &format!("{} per 1,000 words", capitalized(rate_label(key))),
            value.to_string(),
            theirs.map(|t| t.to_string()),
        );
    }
    for (key, dist) in &profile.passages {
        if dist.n == 0 {
            continue;
        }
        row(
            &format!("{} (median per passage)", capitalized(passage_label(key))),
            dist.median.to_string(),
            contrast
                .and_then(|c| c.passages.get(key))
                .filter(|d| d.n > 0)
                .map(|d| d.median.to_string()),
        );
    }
    let zero: Vec<&str> = profile
        .rates
        .iter()
        .filter(|(_, v)| **v == 0.0)
        .map(|(k, _)| rate_label(k))
        .collect();
    if !zero.is_empty() {
        let _ = writeln!(doc, "\nThe source never uses: {}.", zero.join(", "));
    }

    doc.push_str("\n## Transitions\n\n");
    if profile.transitions.is_empty() {
        doc.push_str("The source rarely opens a sentence with a connective.\n");
    } else {
        let used = profile
            .transitions
            .iter()
            .take(10)
            .map(|t| format!("{} ({})", capitalized(t.connective), t.count))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(doc, "Sentence-initial connectives in the source: {used}.");
    }
    if !profile.never_opens_with.is_empty() {
        let never = profile
            .never_opens_with
            .iter()
            .map(|c| capitalized(c))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(doc, "\nNever opens a sentence with: {never}.");
    }

    let (soft, hard): (Vec<&Candidate>, Vec<&Candidate>) =
        kept.iter().partition(|c| c.def.engine == "inferential");
    if !hard.is_empty() {
        doc.push_str("\n## Hard rules (checked deterministically)\n\n");
        for rule in hard {
            let _ = write!(
                doc,
                "- **{}**: {}",
                rule.id,
                rule.def.description.as_deref().unwrap_or("")
            );
            if let Some(example) = rule.def.examples.first() {
                let _ = write!(
                    doc,
                    "\n  Not: \"{}\"\n  But: \"{}\"",
                    example.bad.trim(),
                    example.good.trim()
                );
            }
            doc.push('\n');
        }
    }
    if !soft.is_empty() {
        doc.push_str("\n## Soft rules (checked by the AI judge)\n");
        for rule in soft {
            let _ = writeln!(
                doc,
                "\n### {}\n\n{}\n\n{}\n",
                rule.id,
                rule.def.description.as_deref().unwrap_or(""),
                rule.def.rubric.as_deref().unwrap_or("").trim()
            );
            doc.push_str("Reads like the source:\n");
            for example in rule.def.pass_examples.iter().take(3) {
                let _ = writeln!(doc, "- {}", one_line(example));
            }
            doc.push_str("\nNot like this:\n");
            for example in rule.def.flag_examples.iter().take(3) {
                let _ = writeln!(doc, "- {}", one_line(example));
            }
        }
    }
    doc
}

#[cfg(test)]
mod tests {
    use super::super::profile::measure;
    use super::*;

    #[test]
    fn style_guide_renders_profile_comparison_and_workflow() {
        let source = "The court denied the motion. But the record shows a dispute about who \
                      knew what, when, and why it mattered. So the case goes to trial.";
        let ours = measure(&[(source, false)]);
        let theirs = measure(&[("Moreover, the analysis is comprehensive and robust.", false)]);
        let guide = style_guide(
            "house",
            "briefs/",
            Path::new("out/house"),
            &ours,
            Some(&theirs),
            &[],
        );
        assert!(guide.starts_with("# Writing style: house"));
        assert!(guide.contains("lawlint --rule-dir out/house --format prompt draft.md"));
        assert!(guide.contains("| Measure | Source | AI drafts |"));
        assert!(guide.contains("But (1)"), "{guide}");
        assert!(guide.contains("Never opens a sentence with: "), "{guide}");
        let plain = style_guide("house", "briefs/", Path::new("out"), &ours, None, &[]);
        assert!(plain.contains("| Measure | Source |\n"));
    }
}
