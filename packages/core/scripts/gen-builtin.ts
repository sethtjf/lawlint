// Generates src/generated/builtin.ts from crates/lawlint-core/builtin.
// `bun run --cwd packages/core gen:builtin` rewrites; `--check` fails when stale.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "../../../crates/lawlint-core/builtin");
const OUT = join(import.meta.dir, "../src/generated/builtin.ts");
const check = process.argv.includes("--check");

const files: Record<string, string> = {};
files["style.yaml"] = readFileSync(join(ROOT, "style.yaml"), "utf8");
for (const name of readdirSync(join(ROOT, "rules")).sort()) {
  if (name.endsWith(".md")) {
    files[`rules/${name}`] = readFileSync(join(ROOT, "rules", name), "utf8");
  }
}

const body = `// Generated by scripts/gen-builtin.ts — do not edit.
// The built-in rule package, embedded like Rust's include_dir!.
export const BUILTIN_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

const existing = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return undefined;
  }
})();

if (check) {
  if (existing !== body) {
    console.error(
      "src/generated/builtin.ts is stale — run `bun run --cwd packages/core gen:builtin`",
    );
    process.exit(1);
  }
  console.log("src/generated/builtin.ts is up to date.");
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} (${Object.keys(files).length} files)`);
}
